// Offline conversion of OSM latitude/longitude into metre-scale game geometry.
// Uniform scaling reconciles mapped centre lines with official lap distances.
import fs from 'node:fs/promises';

const references = JSON.parse(await fs.readFile(new URL('../art/references/circuits.json', import.meta.url), 'utf8'));
const layouts = {};
for (const ref of references) {
  const [latitude, longitude] = ref.finish;
  const points = ref.coordinates.map(([lat, lon]) => [
    (lon - longitude) * Math.cos(latitude * Math.PI / 180) * 111195,
    -(lat - latitude) * 111195,
  ]);
  // Start on the projected finish line, including on sparsely mapped straights.
  let closest = Infinity, at = 0, finish;
  for (let i = 0; i < points.length; i++) {
    const a = points[i], b = points[(i + 1) % points.length];
    const dx = b[0] - a[0], dz = b[1] - a[1];
    const t = Math.max(0, Math.min(1, -(a[0] * dx + a[1] * dz) / (dx * dx + dz * dz)));
    const p = [a[0] + t * dx, a[1] + t * dz], distance = Math.hypot(...p);
    if (distance < closest) { closest = distance; at = i; finish = p; }
  }
  const ordered = [finish, ...points.slice(at + 1), ...points.slice(0, at + 1)];
  const unique = ordered.filter((p, i) => !i || Math.hypot(p[0] - ordered[i - 1][0], p[1] - ordered[i - 1][1]) > .25);
  if (Math.hypot(unique.at(-1)[0] - finish[0], unique.at(-1)[1] - finish[1]) < .25) unique.pop();
  const measured = unique.reduce((sum, p, i) => {
    const q = unique[(i + 1) % unique.length];
    return sum + Math.hypot(p[0] - q[0], p[1] - q[1]);
  }, 0);
  const scale = ref.length / measured;
  const positions = unique.map(p => p.map((v, k) => (v - finish[k]) * scale));
  const distances = [0];
  for (let i=1;i<positions.length;i++)distances.push(distances[i-1]+Math.hypot(positions[i][0]-positions[i-1][0],positions[i][1]-positions[i-1][1]));
  const corners = (ref.corners || []).map(corner => {
    const [lat,lon]=corner.coordinate;
    const x=((lon-longitude)*Math.cos(latitude*Math.PI/180)*111195-finish[0])*scale;
    const z=(-(lat-latitude)*111195-finish[1])*scale;
    const at=positions.reduce((best,p,i)=>Math.hypot(p[0]-x,p[1]-z)<Math.hypot(positions[best][0]-x,positions[best][1]-z)?i:best,0);
    return {number:corner.number,name:corner.name,s:+distances[at].toFixed(2)};
  }).sort((a,b)=>a.s-b.s);
  layouts[ref.id] = {
    points: positions.map(p => p.map(v => +v.toFixed(3))), corners,
    length: ref.length, width: ref.width, pitSide: ref.pitSide,
    direction: ref.direction, layoutVersion: 'real-2026-1', source: ref.source.url,
  };
}
await fs.writeFile(new URL('../dist/circuit-layouts.js', import.meta.url),
  '// Generated by tools/build-circuits.mjs. © OpenStreetMap contributors, ODbL 1.0.\n' +
  '// https://www.openstreetmap.org/copyright — source: art/references/circuits.json\n' +
  'export const CIRCUIT_LAYOUTS = ' + JSON.stringify(layouts) + ';\n');
console.log(`${references.length} circuiti reali preparati.`);
